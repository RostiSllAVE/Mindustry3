"""Generate isolated payload subclasses. Native recipes/progress remain in the native families."""
import ast
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
tree=ast.parse((ROOT/'tools/generate-layer-families.py').read_text(encoding='utf-8'))
guard=next(ast.literal_eval(n.value) for n in tree.body if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='guard' for t in n.targets))
guard+='''
@Override public void onRemoved(){}
@Override public boolean canControlSelect(Unit unit){return false;}
'''
payload='''
@Override public void moveOutPayload(){LayerPayloadBehavior.moveOut(owner,this);}
@Override public void dumpPayload(){LayerPayloadBehavior.dump(owner,this);}
'''
families={
'units.UnitFactory.UnitFactoryBuild':payload+'@Override public void onCommand(arc.math.geom.Vec2 target){commandPos=target==null?null:target.cpy();}',
'units.Reconstructor.ReconstructorBuild':payload+'@Override public void onCommand(arc.math.geom.Vec2 target){commandPos=target==null?null:target.cpy();}',
'payloads.Constructor.ConstructorBuild':payload,
'payloads.PayloadLoader.PayloadLoaderBuild':payload,
'payloads.PayloadUnloader.PayloadUnloaderBuild':payload,
'payloads.PayloadSource.PayloadSourceBuild':payload,
'payloads.PayloadVoid.PayloadVoidBuild':payload,
'payloads.PayloadDeconstructor.PayloadDeconstructorBuild':payload+'''@Override public void updateTile(){LayerPayloadBehavior.drainDeconstructionLiquid(this);super.updateTile();}''',
'payloads.PayloadConveyor.PayloadConveyorBuild':'''@Override public void updateTile(){LayerPayloadBehavior.conveyor(owner,this);}
@Override public void unitOn(Unit unit){}''',
'payloads.PayloadRouter.PayloadRouterBuild':'''@Override public void updateTile(){LayerPayloadBehavior.conveyor(owner,this);controlTime-=arc.util.Time.delta;smoothRot=arc.math.Mathf.slerpDelta(smoothRot,rotdeg(),.2f);}
@Override public void unitOn(Unit unit){}''',
'units.UnitAssembler.UnitAssemblerBuild':payload+'''
@Override public void updatePayload(){super.updatePayload();LayerPayloadBehavior.reconcileAssembler(this,readUnits);}
@Override public void updateTile(){updatePayload();LayerPayloadBehavior.assembler(owner,this);}
@Override public void spawned(){LayerPayloadBehavior.spawnAssembler(owner,this);}
@Override public boolean checkSolid(arc.math.geom.Vec2 target,boolean same){return LayerPayloadBehavior.assemblyBlocked(owner,this,target);}
''',
'units.UnitAssemblerModule.UnitAssemblerModuleBuild':payload+'''
@Override public void findLink(){LayerPayloadBehavior.findAssembler(owner,this);}
@Override public void updateTile(){LayerPayloadBehavior.module(owner,this);}
''',
'payloads.PayloadMassDriver.PayloadDriverBuild':payload+'''
@Override public void updateTile(){LayerPayloadBehavior.massDriver(owner,this);}
@Override protected boolean linkValid(){return LayerPayloadBehavior.driverLink(owner,this)!=null;}
''',
'units.UnitCargoLoader.UnitTransportSourceBuild':'''@Override public void updateTile(){LayerPayloadBehavior.cargoLoader(owner,this);}
@Override public void spawned(int id){readUnitId=id;buildProgress=0;}''',
'units.UnitCargoUnloadPoint.UnitCargoUnloadPointBuild':'',
}
full=lambda name:'mindustry.world.blocks.'+name
text='''package fpv.construction;
// Generated by tools/generate-layer-payloads.py.
import arc.math.geom.Geometry;
import mindustry.gen.*;
import mindustry.game.Team;
import mindustry.world.*;

/** Native payload recipes/transport, isolated at release and native tile-RPC boundaries. */
final class LayerPayloadFamilies {
    static boolean supports(Class<?> type){return
'''
text+=' ||\n'.join('        type=='+full(name)+'.class' for name in families)+';\n    }\n'
text+='    static Building create(LayerBuildingAdapter owner,Block block,Class<?> type){\n'
for name,extra in families.items():
    outer,inner=name.rsplit('.',1)
    text+='        if(type=='+full(name)+'.class)return (('+full(outer)+')block).new '+inner+'(){\n'
    text+='\n'.join('            '+line for line in (guard+'\n'+extra).strip().splitlines())+'\n        };\n'
text+='        throw new IllegalArgumentException("Unsupported upper payload family: "+type.getName());\n    }\n'
text+='    static void reconcileReferences(LayerBuildingAdapter owner){for(var entry:owner.entries()){if(entry.building() instanceof mindustry.world.blocks.units.UnitAssembler.UnitAssemblerBuild assembler)assembler.updatePayload();else if(entry.building() instanceof mindustry.world.blocks.units.UnitCargoLoader.UnitTransportSourceBuild cargo)LayerPayloadBehavior.reconcileCargo(owner,cargo);}}\n}\n'
(ROOT/'src/main/java/fpv/construction/LayerPayloadFamilies.java').write_text('\n'.join(line.rstrip() for line in text.splitlines())+'\n',encoding='utf-8')
print(f'Generated {len(families)} payload adapters')
